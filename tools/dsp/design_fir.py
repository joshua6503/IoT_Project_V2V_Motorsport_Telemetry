#!/usr/bin/env python3
"""Design the brake-pressure low-pass FIR (window method) and write its C header.

REQ-F-015, DEC-009. Coefficients come from scipy.signal.firwin (DC gain = 1).

Outputs (paths relative to the repo root):
    firmware/common/include/fir_brake_coeffs.h   always
    tests/unit/fir_reference.h                   with --reference (golden test data)
    tools/dsp/out/fir_response.png               with --plot

Usage (PowerShell, from the repo root, venv active):
    python tools/dsp/design_fir.py --fs 20 --fc 2 --taps 9 --window hamming --reference --plot

The output is deterministic: running the same command twice gives identical files,
so `git diff` shows whether the committed headers match the command in their banner.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from scipy import signal

ROOT = Path(__file__).resolve().parents[2]
COEFFS_H = ROOT / "firmware" / "common" / "include" / "fir_brake_coeffs.h"
REFERENCE_H = ROOT / "tests" / "unit" / "fir_reference.h"
OUT_DIR = ROOT / "tools" / "dsp" / "out"

# Golden-test input (deterministic): step + sine at fc/2 + sine at 4*fc + seeded noise.
REF_LEN = 200
REF_SEED = 9
REF_STEP_AT = 20
REF_STEP_AMP = 0.5
REF_SINE_AMP = 0.2
REF_NOISE_STD = 0.05

# Chart colours: categorical slots 1 and 2 of the dataviz reference palette.
COLOR_X = "#2a78d6"  # raw / response
COLOR_Y = "#eb6834"  # filtered
COLOR_MUTED = "#6b6a63"


def c_float(v: float) -> str:
    """float32 value as a C float literal that round-trips exactly."""
    s = f"{float(np.float32(v)):.9g}"
    if "." not in s and "e" not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


def c_array(name: str, values: np.ndarray, per_line: int = 4) -> str:
    items = [c_float(v) for v in values]
    lines = [", ".join(items[i : i + per_line]) for i in range(0, len(items), per_line)]
    body = ",\n    ".join(lines)
    return f"static const float {name}[{len(values)}] = {{\n    {body},\n}};\n"


def command_line(args: argparse.Namespace, *, reference: bool) -> str:
    cmd = (
        f"python tools/dsp/design_fir.py --fs {args.fs:g} --fc {args.fc:g} "
        f"--taps {args.taps} --window {args.window}"
    )
    return cmd + (" --reference" if reference else "")


def design(fs: float, fc: float, taps: int, window: str) -> np.ndarray:
    h = signal.firwin(taps, fc, window=window, pass_zero="lowpass", fs=fs)
    return h.astype(np.float32)


def render_coeffs(h: np.ndarray, args: argparse.Namespace) -> str:
    delay_ms = (args.taps - 1) / (2.0 * args.fs) * 1000.0
    return (
        "/* AUTO-GENERATED by tools/dsp/design_fir.py — do not edit.\n"
        f" * Command: {command_line(args, reference=False)}\n"
        f" * Design:  scipy.signal.firwin, low-pass, window={args.window}, N={args.taps} taps,\n"
        f" *          fs={args.fs:g} Hz, fc={args.fc:g} Hz (-6 dB), DC gain 1.\n"
        f" * Group delay (N-1)/(2*fs) = {delay_ms:g} ms.\n"
        " * DEC-009 / REQ-F-015: ASSUMPTION (to validate with the FFT of a raw capture).\n"
        " */\n"
        "#ifndef FIR_BRAKE_COEFFS_H\n"
        "#define FIR_BRAKE_COEFFS_H\n"
        "\n"
        f"#define FIR_BRAKE_N     {args.taps}u\n"
        f"#define FIR_BRAKE_FS_HZ {c_float(args.fs)}\n"
        f"#define FIR_BRAKE_FC_HZ {c_float(args.fc)}\n"
        "\n"
        + c_array("fir_brake_h", h)
        + "\n#endif /* FIR_BRAKE_COEFFS_H */\n"
    )


def reference_input(fs: float, fc: float) -> np.ndarray:
    n = np.arange(REF_LEN)
    t = n / fs
    rng = np.random.default_rng(REF_SEED)
    x = (
        REF_STEP_AMP * (n >= REF_STEP_AT)
        + REF_SINE_AMP * np.sin(2 * np.pi * (fc / 2) * t)
        + REF_SINE_AMP * np.sin(2 * np.pi * (4 * fc) * t)
        + REF_NOISE_STD * rng.standard_normal(REF_LEN)
    )
    return x.astype(np.float32)


def render_reference(h: np.ndarray, args: argparse.Namespace) -> str:
    x = reference_input(args.fs, args.fc)
    # Reference in float64 from the exact float32 values the C code sees.
    y = np.convolve(x.astype(np.float64), h.astype(np.float64))[: len(x)]
    return (
        "/* AUTO-GENERATED by tools/dsp/design_fir.py — do not edit.\n"
        f" * Command: {command_line(args, reference=True)}\n"
        " * Golden data for test_fir_filter.c: y = numpy.convolve(x, fir_brake_h)[:len(x)].\n"
        f" * x = {REF_STEP_AMP:g}*step(n>={REF_STEP_AT}) + {REF_SINE_AMP:g}*sin(fc/2) "
        f"+ {REF_SINE_AMP:g}*sin(4*fc) + N(0,{REF_NOISE_STD:g}) noise, seed {REF_SEED}.\n"
        " */\n"
        "#ifndef FIR_REFERENCE_H\n"
        "#define FIR_REFERENCE_H\n"
        "\n"
        f"#define FIR_REF_N   {args.taps}u /**< taps the reference was computed with */\n"
        f"#define FIR_REF_LEN {REF_LEN}u\n"
        "\n"
        + c_array("fir_ref_x", x)
        + "\n"
        + c_array("fir_ref_y", y.astype(np.float32))
        + "\n#endif /* FIR_REFERENCE_H */\n"
    )


def plot_response(h: np.ndarray, args: argparse.Namespace, path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    f, H = signal.freqz(h.astype(np.float64), worN=2048, fs=args.fs)
    mag_db = 20 * np.log10(np.maximum(np.abs(H), 1e-12))

    fig, ax = plt.subplots(figsize=(8, 4.5), dpi=120)
    ax.plot(f, mag_db, color=COLOR_X, linewidth=1.5)
    ax.axvline(args.fc, color=COLOR_MUTED, linestyle="--", linewidth=1)
    ax.annotate(f"fc = {args.fc:g} Hz", (args.fc, -20), xytext=(4, 0),
                textcoords="offset points", color=COLOR_MUTED, fontsize=9)
    ax.axhline(-6, color=COLOR_MUTED, linestyle=":", linewidth=1)
    ax.annotate("-6 dB", (args.fs / 2, -6), xytext=(-30, 4), textcoords="offset points",
                color=COLOR_MUTED, fontsize=9)
    ax.set_xlim(0, args.fs / 2)
    ax.set_ylim(max(mag_db.min() - 5, -100), 5)
    ax.set_xlabel("Frequency (Hz)")
    ax.set_ylabel("Magnitude (dB)")
    ax.set_title(f"Brake FIR: N={args.taps}, {args.window}, fs={args.fs:g} Hz, fc={args.fc:g} Hz")
    ax.grid(True, color="#e4e3dd", linewidth=0.8)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    plt.close(fig)


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT).as_posix()}")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--fs", type=float, required=True, help="sample rate in Hz")
    p.add_argument("--fc", type=float, required=True, help="cutoff in Hz (-6 dB point)")
    p.add_argument("--taps", type=int, required=True, help="number of taps N")
    p.add_argument("--window", default="hamming", help="scipy window name (default hamming)")
    p.add_argument("--reference", action="store_true", help="also write tests/unit/fir_reference.h")
    p.add_argument("--plot", action="store_true", help="save tools/dsp/out/fir_response.png")
    args = p.parse_args()

    if args.taps < 1 or args.taps > 65535:
        p.error("--taps must be in 1..65535")
    if not 0 < args.fc < args.fs / 2:
        p.error("--fc must be between 0 and fs/2")
    if args.reference and 4 * args.fc >= args.fs / 2:
        print("warning: 4*fc is at or above Nyquist; the reference input aliases", file=sys.stderr)

    h = design(args.fs, args.fc, args.taps, args.window)
    print(f"h = {np.array2string(h, precision=6)}  sum = {float(h.astype(np.float64).sum()):.7f}")
    print(f"group delay = {(args.taps - 1) / (2 * args.fs) * 1000:g} ms")

    write_text(COEFFS_H, render_coeffs(h, args))
    if args.reference:
        write_text(REFERENCE_H, render_reference(h, args))
    if args.plot:
        path = OUT_DIR / "fir_response.png"
        plot_response(h, args, path)
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
